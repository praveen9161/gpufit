// Package claims generates DRA ResourceClaimTemplates that pick GPUs by
// GPUFit score.
//
// DRA doesn't rank devices by score: among devices that pass a CEL selector it
// takes the first ones that fit. To still get "the best GPUs that are free",
// the template lists firstAvailable options from strictest to loosest, e.g.
// score >= 95, then >= 90, then >= 80. The scheduler uses the first option it
// can satisfy.
package claims

import (
	"fmt"
	"io"
	"regexp"
	"slices"
	"strings"
	"text/template"

	"github.com/praveen9161/gpufit/agent/internal/fitness"
)

// maxOptions is the most firstAvailable options we generate. Kept small so the
// YAML stays readable and within API limits.
const maxOptions = 8

// DefaultPrefer are the tiers tried before the minimum score.
var DefaultPrefer = []int{95, 90}

var dnsLabel = regexp.MustCompile(`^[a-z0-9]([-a-z0-9]*[a-z0-9])?$`)

// Options describe the claim a user wants: "N GPUs fit for <workload>, score at least <Min>".
type Options struct {
	Name        string // ResourceClaimTemplate name; defaults to "<workload>-min<Min>-<Count>gpu"
	Namespace   string
	Workload    string // must be a fitness profile name, e.g. "training"
	Count       int    // number of GPUs
	Min         int    // lowest acceptable score, 0-100
	Prefer      []int  // higher scores to try first; values <= Min are ignored
	DeviceClass string
}

// Tiers returns the scores to try, highest first, always ending with min.
func Tiers(min int, prefer []int) ([]int, error) {
	if min < 0 || min > 100 {
		return nil, fmt.Errorf("min score %d not in [0, 100]", min)
	}
	tiers := []int{min}
	for _, p := range prefer {
		if p > 100 {
			return nil, fmt.Errorf("preferred score %d > 100", p)
		}
		if p > min && !slices.Contains(tiers, p) {
			tiers = append(tiers, p)
		}
	}
	slices.Sort(tiers)
	slices.Reverse(tiers)
	if len(tiers) > maxOptions {
		return nil, fmt.Errorf("%d tiers, at most %d allowed", len(tiers), maxOptions)
	}
	return tiers, nil
}

// Write renders the ResourceClaimTemplate YAML for o.
func Write(w io.Writer, o Options) error {
	if !isWorkload(o.Workload) {
		return fmt.Errorf("unknown workload %q, want one of %s", o.Workload, strings.Join(workloads(), ", "))
	}
	if o.Count < 1 {
		return fmt.Errorf("count must be at least 1, got %d", o.Count)
	}
	if o.Name == "" {
		o.Name = fmt.Sprintf("%s-min%d-%dgpu", o.Workload, o.Min, o.Count)
	}
	if !dnsLabel.MatchString(o.Name) || len(o.Name) > 63 {
		return fmt.Errorf("invalid name %q: use lowercase letters, digits and '-'", o.Name)
	}
	tiers, err := Tiers(o.Min, o.Prefer)
	if err != nil {
		return err
	}
	return tmpl.Execute(w, struct {
		Options
		Tiers []int
	}{o, tiers})
}

func workloads() []string {
	var names []string
	for _, p := range fitness.DefaultProfiles {
		names = append(names, p.Name)
	}
	return names
}

func isWorkload(name string) bool { return slices.Contains(workloads(), name) }

var tmpl = template.Must(template.New("claim").Parse(`# Generated by gpufit-claim: {{.Count}} GPU(s) for {{.Workload}}, score >= {{.Min}}.
# Options are tried in order; the scheduler uses the first one it can satisfy,
# so the job gets the best tier that is still free.
apiVersion: resource.k8s.io/v1
kind: ResourceClaimTemplate
metadata:
  name: {{.Name}}
  namespace: {{.Namespace}}
  labels:
    gpufit.io/workload: {{.Workload}}
    gpufit.io/min-score: "{{.Min}}"
spec:
  spec:
    devices:
      requests:
      - name: gpus
        firstAvailable:
{{- range .Tiers}}
        - name: min{{.}}
          deviceClassName: {{$.DeviceClass}}
          allocationMode: ExactCount
          count: {{$.Count}}
          selectors:
          - cel:
              expression: device.attributes["gpufit.io"].{{$.Workload}}Score >= {{.}}
{{- end}}
`))
